// Regenerates docs/TEST-RESULTS.md from a real Vitest run.
// Run with: npm run test:report
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, unlinkSync, existsSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const jsonPath = resolve(root, '.test-results.json')
const outPath = resolve(root, 'docs/TEST-RESULTS.md')

if (existsSync(jsonPath)) unlinkSync(jsonPath)
try {
  execSync('npx vitest run --reporter=json --outputFile=.test-results.json', {
    cwd: root,
    stdio: 'inherit',
  })
} catch (error) {
  if (!existsSync(jsonPath)) throw error
  // Still write every failed case and its diagnostics, never leave a stale pass.
  process.exitCode = 1
}

const raw = JSON.parse(readFileSync(jsonPath, 'utf8'))
if (existsSync(jsonPath)) unlinkSync(jsonPath)

const iso = new Date()
const pad = (n) => String(n).padStart(2, '0')
const date = `${iso.getFullYear()}-${pad(iso.getMonth() + 1)}-${pad(iso.getDate())}`
const time = `${pad(iso.getHours())}:${pad(iso.getMinutes())}`

const relPath = (abs) => {
  const parts = abs.split(/[\\/]/)
  return parts.slice(parts.lastIndexOf('AIgoNavigator') + 1).join('/')
}
// A few report files are not named after their test basename (see
// docs/bug-reports/README.md for the convention).
const REPORT_NAME_OVERRIDES = {
  'api/tutor/handler.test.ts': 'tutorHandler',
  'src/assets/index.test.ts': 'assets',
}
const reportFor = (testPath) => {
  const base =
    REPORT_NAME_OVERRIDES[testPath] ??
    testPath
      .split('/')
      .pop()
      .replace(/\.test\.tsx?$/, '')
  return `docs/bug-reports/${base}.md`
}
const cell = (text) => String(text).replace(/\|/g, '\\|')

const files = raw.testResults
  .map((f) => {
    const path = relPath(f.name)
    return {
      path,
      status: f.status,
      duration: Math.round(f.endTime - f.startTime),
      cases: f.assertionResults.map((a) => {
        // Vitest joins describe() names with spaces into fullName, so the
        // bare case title is authoritative (plus ancestorTitles for context).
        const ancestors = (a.ancestorTitles ?? []).join(' › ')
        return {
          title: a.title,
          group: ancestors,
          status: a.status,
          duration: Math.round(a.duration ?? 0),
          error: a.failureMessages?.join('\n') ?? '',
        }
      }),
    }
  })
  .sort((a, b) => a.path.localeCompare(b.path))

const total = raw.numTotalTests
const passed = raw.numPassedTests
const failed = raw.numFailedTests
const skipped = total - passed - failed

const missingReports = files
  .map((f) => reportFor(f.path))
  .filter((p) => !existsSync(resolve(root, p)))
if (missingReports.length) {
  console.warn(
    `Warning: no companion report for: ${missingReports.join(', ')}\n` +
      'Add one per docs/bug-reports/README.md.',
  )
}

let md = `# Test Results

Generated by \`npm run test:report\` on ${date} at ${time}.
Do not edit by hand — re-run the command instead.

> Companion documentation (what each test guards against, known gaps) lives in
> [\`docs/bug-reports/\`](bug-reports/README.md). This file records the concrete
> test cases and whether they passed.

## Summary

| Metric | Value |
| --- | --- |
| Test files | ${files.length} |
| Test cases | ${total} |
| Passed | ${passed} |
| Failed | ${failed} |
| Skipped/other | ${skipped} |
| Overall | ${failed === 0 ? '✅ PASS' : '❌ FAIL'} |

## Per-file results

| Test file | Cases | Passed | Duration | Result | Report |
| --- | --- | --- | --- | --- | --- |
${files
  .map((f) => {
    const ok = f.cases.filter((c) => c.status === 'passed').length
    const mark = f.cases.every((c) => c.status === 'passed') ? '✅' : '❌'
    return `| \`${f.path}\` | ${f.cases.length} | ${ok} | ${f.duration} ms | ${mark} | [\`${reportFor(f.path)}\`](${reportFor(f.path).replace('docs/', '')}) |`
  })
  .join('\n')}

## Test cases

${files
  .map((f) => {
    const ok = f.cases.filter((c) => c.status === 'passed').length
    const mark = f.cases.every((c) => c.status === 'passed') ? '✅' : '❌'
    const rows = f.cases
      .map((c, i) => {
        const name = c.group ? `${c.group} › ${c.title}` : c.title
        return `| ${i + 1} | ${cell(name)} | ${c.status === 'passed' ? '✅ passed' : `❌ ${c.status}`} | ${c.duration} ms |`
      })
      .join('\n')
    const failures = f.cases
      .filter((c) => c.status !== 'passed' && c.error)
      .map((c) => `\n**Failure — ${c.title}**\n\n\`\`\`\n${c.error}\n\`\`\`\n`)
      .join('\n')
    return `### \`${f.path}\` — ${ok}/${f.cases.length} ${mark}\n\n| # | Test case | Result | Duration |\n| --- | --- | --- | --- |\n${rows}\n${failures}`
  })
  .join('\n')}
`

writeFileSync(outPath, md)
console.log(`Wrote ${outPath} (${passed}/${total} passing)`)
